"""Regenerates docs/SETTINGS.md from the settings spec so the reference can never drift from the code.

    python tools/gen_settings_doc.py          # rewrite the file
    python tools/gen_settings_doc.py --check  # exit 1 if it is out of date (used by the test-suite)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jobhunter import companies as co  # noqa: E402
from jobhunter.config import load_base  # noqa: E402
from jobhunter.settings import SECTIONS, get_path, to_text  # noqa: E402

TARGET = ROOT / "docs" / "SETTINGS.md"


def render() -> str:
    base = load_base(ROOT / "config.example.yaml")
    out = ["# Settings reference", "",
           "<!-- generated by tools/gen_settings_doc.py - do not edit by hand -->", "",
           "Every setting below can be changed in the web UI under **Settings** (and **Companies**). "
           "Changes are stored in the database, apply immediately and are shared by the web app and the command-line "
           "scraper. Each page has *Reset to defaults*. The *Path* column is the key you can also use in `config.yaml`.", ""]
    for s in SECTIONS:
        out += [f"## {s.title}", "", s.intro, "",
                "| Setting | Path | Default | What it does |", "|---|---|---|---|"]
        for f in s.fields:
            d = get_path(base, f.path)
            if f.kind == "textarea" and len(str(d)) > 60:
                default = "built-in text"
            else:
                default = to_text(f, d).replace("\n", ", ") if f.kind != "bool" else ("on" if d else "off")
            if len(default) > 60:
                default = default[:57] + "..."
            default = f"`{default}`" if default else "*(empty)*"
            doc = (f.help or "").replace("|", "\\|")
            unit = f" Unit: {f.unit}." if f.unit else ""
            rng = f" Allowed: {f.min:g}-{f.max:g}." if f.min is not None and f.max is not None else ""
            out.append(f"| {f.label} | `{f.path}` | {default} | {doc}{unit}{rng} |")
        out.append("")
    out += ["## Companies", "",
            "Managed on the **Companies** page. Each entry has a name, a **tier** (1 = big / high-paying, 2 = decent) "
            "and a career-site type with its own details:", "",
            "| Type | Fields | Where to find them |", "|---|---|---|"]
    for key, a in co.ATS.items():
        fields = ", ".join(f"`{k}`{'*' if req else ''}" for k, _, req, _ in a["fields"]) or "none"
        how = a["how"].replace("<b>", "**").replace("</b>", "**").replace("<code>", "`").replace("</code>", "`")
        out.append(f"| {a['label']} (`{key}`) | {fields} | {how} |")
    out += ["", "`*` = required. A company can be paused without deleting it.", "",
            "## Only in `config.yaml`", "",
            "| Key | Default | Why it isn't in the UI |", "|---|---|---|",
            f"| `web.host` | `{base['web']['host']}` | changing the address from the page you're using could lock you out; needs a restart |",
            f"| `web.port` | `{base['web']['port']}` | same; pick a port nothing else (e.g. Pi-hole) uses |",
            f"| `db_path` | `{base['db_path'].replace(str(ROOT) + '/', '')}` | where the database lives; it holds the settings themselves |",
            "| `manual_links` | list | quick links on the Status page; rarely changed |", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.exists() and TARGET.read_text() == text else 1)
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(text)
    print("wrote", TARGET)
